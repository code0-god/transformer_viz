//! Exports deterministic curriculum token examples from the canonical tokenizer asset.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::PathBuf;

use nanogpt_schema::{TokenId, TokenInfo, TokenKind};
use nanogpt_tokenizer::Tokenizer;

const EXAMPLES: [(&str, &str); 3] = [
    ("the-cat", "the cat"),
    ("the-cats", "the cats"),
    ("korean-han", "한"),
];

fn render_token(token: &TokenInfo) -> Result<String, serde_json::Error> {
    let kind = match token.kind {
        TokenKind::Bos => "bos",
        TokenKind::Eos => "eos",
        TokenKind::Unknown => "unknown",
        TokenKind::Byte => "byte",
    };
    Ok(format!(
        "{{ id: {}, display: {}, piece: {}, byteStart: {}, byteEnd: {}, kind: \"{}\" }}",
        token.id.0,
        serde_json::to_string(&token.display)?,
        serde_json::to_string(&token.piece)?,
        token
            .byte_start
            .map_or_else(|| "null".to_owned(), |value| value.to_string()),
        token
            .byte_end
            .map_or_else(|| "null".to_owned(), |value| value.to_string()),
        kind,
    ))
}

fn render_tokens(tokens: &[TokenInfo]) -> Result<String, serde_json::Error> {
    tokens
        .iter()
        .map(render_token)
        .collect::<Result<Vec<_>, _>>()
        .map(|items| format!("[{}]", items.join(", ")))
}

fn main() -> Result<(), Box<dyn Error>> {
    let mut arguments = std::env::args_os().skip(1);
    let input = PathBuf::from(arguments.next().ok_or_else(|| {
        io::Error::new(io::ErrorKind::InvalidInput, "missing tokenizer input path")
    })?);
    let output = PathBuf::from(arguments.next().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            "missing TypeScript output path",
        )
    })?);
    if arguments.next().is_some() {
        return Err(
            io::Error::new(io::ErrorKind::InvalidInput, "unexpected extra argument").into(),
        );
    }

    let tokenizer = Tokenizer::from_json(&fs::read_to_string(input)?)?;
    let config = tokenizer.config();
    if (
        config.bos_id,
        config.eos_id,
        config.unk_id,
        config.byte_offset,
    ) != (TokenId(0), TokenId(1), TokenId(2), 3)
    {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "curriculum tokenizer requires BOS=0, EOS=1, UNK=2, byte_offset=3",
        )
        .into());
    }

    let mut rendered = String::from(
        "// Generated by export_curriculum_examples. Do not edit manually.\n\
// allow: SIZE_OK — deterministic generated token data table\n\n\
export type CurriculumToken = {\n\
\x20\x20readonly id: number;\n\
\x20\x20readonly display: string;\n\
\x20\x20readonly piece: readonly number[];\n\
\x20\x20readonly byteStart: number | null;\n\
\x20\x20readonly byteEnd: number | null;\n\
\x20\x20readonly kind: \"bos\" | \"eos\" | \"unknown\" | \"byte\";\n\
};\n\n\
export type CurriculumTokenExample = {\n\
\x20\x20readonly id: \"the-cat\" | \"the-cats\" | \"korean-han\";\n\
\x20\x20readonly text: string;\n\
\x20\x20readonly displayEncoding: readonly CurriculumToken[];\n\
\x20\x20readonly generationPrefix: readonly CurriculumToken[];\n\
};\n\n\
// biome-ignore format: generated deterministic data\n\
export const curriculumTokenExamples = [\n",
    );
    for (id, text) in EXAMPLES {
        let display = tokenizer.encode(text);
        let prefix = tokenizer.generation_prompt(text)?;
        write!(
            &mut rendered,
            "  {{\n    id: {},\n    text: {},\n    displayEncoding: {},\n    generationPrefix: {},\n  }},\n",
            serde_json::to_string(id)?,
            serde_json::to_string(text)?,
            render_tokens(&display.tokens)?,
            render_tokens(&prefix.tokens)?,
        )?;
    }
    rendered.push_str("] as const satisfies readonly CurriculumTokenExample[];\n");
    fs::write(output, rendered)?;
    Ok(())
}
